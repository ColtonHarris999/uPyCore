#!/usr/bin/env python3
"""Write iocore/rtl/usb/usb_trans_mc.svh: no2usb's transaction microcode
(vendor/no2usb/utils/microcode.py, the ROM its usb_trans.v loads with
INIT_FILE "usb_trans_mc.hex") as a SystemVerilog function, so the ROM is
logic in the ASIC flow (iocore/rtl/usb/ice40_cells.sv). Rerun after a
no2usb update:

    python3 iocore/tools/gen_usb_mc.py
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "vendor" / "no2usb" / "utils" / "microcode.py"
OUT = ROOT / "iocore" / "rtl" / "usb" / "usb_trans_mc.svh"


def main() -> int:
    r = subprocess.run([sys.executable, "-I", str(SRC)], capture_output=True, text=True, check=True)
    words = [int(w, 16) for w in r.stdout.split()]
    commit = subprocess.run(["git", "-C", str(SRC.parents[1]), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    lines = [
        "// Generated by iocore/tools/gen_usb_mc.py from vendor/no2usb/utils/microcode.py",
        f"// (no2usb {commit}, MIT). Do not edit. {len(words)} words; the rest read 0.",
        "`ifndef USB_TRANS_MC_SVH",
        "`define USB_TRANS_MC_SVH",
        "function automatic logic [15:0] usb_trans_mc(input logic [7:0] a);",
        "    case (a)",
    ]
    lines += [f"        8'h{i:02x}: return 16'h{w:04x};" for i, w in enumerate(words)]
    lines += ["        default: return 16'h0000;", "    endcase", "endfunction", "`endif", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
