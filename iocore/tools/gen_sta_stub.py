#!/usr/bin/env python3
"""Write iocore/rtl/sta/iocore_top_stub.sv from iocore_top's port list.

The stub stands in for the island in the hart-domain timing run
(upycore/tools/sta/run.py on mpy_soc): every input ends at a flop and every
output starts at one. Rerun after changing iocore_top's ports.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEAD = """// Timing-flow stand-in for the I/O island (iocore/rtl/iocore_top.sv) in the
// hart-domain run of upycore/tools/sta/run.py: the same name, parameters and
// ports, with every input ending at a flop and every output starting at
// one, the way the SRAM macros are stubbed. The island runs on io_clk and is
// timed on its own (iocore/tools/island_measure.py); this keeps it out of
// the hart's register groups. Generated by iocore/tools/gen_sta_stub.py.
"""


def main() -> int:
    src = (ROOT / "iocore/rtl/iocore_top.sv").read_text()
    hdr = src[src.index("module iocore_top"):src.index(");") + 2]
    ports = re.findall(r"\b(input|output)\s+logic\s*(\[[^\]]+\])?\s*(\w+)", hdr)
    ins = [(w, n) for d, w, n in ports if d == "input" and n != "io_clk_i"]
    outs = [(w, n) for d, w, n in ports if d == "output"]
    body = ["    // Inputs end at flops (every bit is a timing endpoint)."]
    body += [f"    (* keep *) logic {w + ' ' if w else ''}q_{n};" for w, n in ins]
    body += ["    always_ff @(posedge io_clk_i) begin"] + [f"        q_{n} <= {n};" for _, n in ins] + ["    end"]
    body.append("    // Outputs start at flops (their own sources, not the inputs).")
    for w, n in outs:
        body += [f"    (* keep *) logic {w + ' ' if w else ''}r_{n};",
                 f"    always_ff @(posedge io_clk_i) r_{n} <= r_{n} + 1'b1;",
                 f"    assign {n} = r_{n};"]
    out = ROOT / "iocore/rtl/sta/iocore_top_stub.sv"
    out.write_text(HEAD + hdr + "\n" + "\n".join(body) + "\nendmodule\n")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
