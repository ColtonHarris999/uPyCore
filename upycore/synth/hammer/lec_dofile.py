#!/usr/bin/env python3
"""Write a Conformal LEC dofile that checks the netlist against the RTL.

Equivalence checking proves the mapped netlist Genus wrote computes
exactly what the RTL does, flop for flop. With the RTL already passing the
hardware test suite, a pass here carries that to the gates.

Run from the design folder after `make syn`:

    python3 ~/upycore/upycore/synth/hammer/lec_dofile.py
    lec -xl -nogui -dofile lec/lec.do

Golden (the reference) is golden/<top>.sv, the SystemVerilog the tests
run, when make_hammer_design.py --sv2v kept it there; otherwise the file in
v/. If Conformal cannot parse the SystemVerilog, pass --golden v to check
against the sv2v output Genus read instead (that skips checking sv2v).

Untested: written without Conformal access. If a command is rejected,
lec/lec.log names it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

LIB = "/home/projects/ee477/cad/pdk/sky130A/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_025C_1v80.lib"

DOFILE = """\
// Generated by lec_dofile.py: {golden} (golden) vs {netlist} (revised)
set log file lec/lec.log -replace
read library -both -liberty {lib}
read design -golden {golden_fmt} {golden}
read design -revised -verilog {netlist}
set root module {top} -golden
set root module {top} -revised
// Flops Genus removed because they are stuck at a constant.
set flatten model -seq_constant
set system mode lec
// Multipliers and dividers: let LEC match the datapath structure.
analyze datapath -merge -verbose
add compared points -all
compare
report verification
report statistics
report compare data -class nonequivalent -class abort -class notcompared
exit -force
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder", nargs="?", default=".", type=Path)
    ap.add_argument("--golden", choices=["sv", "v"], default="sv",
                    help="sv: golden/<top>.sv if present (default); v: the file in v/")
    ap.add_argument("--lib", default=LIB, help="any sky130_fd_sc_hd liberty (cell functions)")
    args = ap.parse_args()

    folder = args.folder.resolve()
    netlists = sorted((folder / "build" / "syn-rundir").glob("*.mapped.v"))
    if not netlists:
        sys.exit("no build/syn-rundir/*.mapped.v; run make syn first")
    netlist = netlists[0]
    top = netlist.name[: -len(".mapped.v")]
    golden = folder / "golden" / f"{top}.sv"
    if args.golden == "v" or not golden.is_file():
        found = sorted((folder / "v").glob(f"{top}.*v"))
        if not found:
            sys.exit(f"no v/{top}.sv or v/{top}.v")
        golden = found[0]
    fmt = "-systemverilog" if golden.suffix == ".sv" else "-verilog2k"

    (folder / "lec").mkdir(exist_ok=True)
    do = folder / "lec" / "lec.do"
    do.write_text(DOFILE.format(golden=golden, netlist=netlist, top=top,
                                golden_fmt=fmt, lib=args.lib))
    print(f"wrote {do.relative_to(folder)}: {golden.relative_to(folder)} vs "
          f"{netlist.relative_to(folder)}")
    print("run: lec -xl -nogui -dofile lec/lec.do")
    print("pass = report verification shows 0 non-equivalent and 0 aborted points")
    return 0


if __name__ == "__main__":
    sys.exit(main())
