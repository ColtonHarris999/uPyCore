#!/usr/bin/env python3
"""Write Hazard3 as one Verilog file, configured like the benchmark runs.

Synthesizing hazard3_cpu_2port as a top uses the defaults in
hdl/hazard3_config.vh, which turn most extensions off. The benchmark runs
(benchmarks/upycore_bench) used the testbench's config_default.vh instead.
This script writes those values in as the defaults, so the synthesized
core is the one that was measured, then inlines every `include.

Configs:
  default    exactly the testbench's config_default.vh (what the cycle
             counts were measured on; includes debug, PMP, triggers and
             extensions the benchmark binaries never execute)
  bench-isa  config_default with the parts the benchmark build cannot use
             turned off: ZBC, ZBKX, ZILSD, ZCLSD, XH3BEXTM (not in its
             -march), debug, triggers, PMP and U-mode. Cycle counts are
             unchanged, because none of these were exercised.

Usage (Hazard3 at commit 8af9929, as benchmarked)::

    hazard3_rtl.py ~/Hazard3 --config bench-isa -o hazard3_cpu_2port.sv
"""

from __future__ import annotations

import argparse
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from flatten_verilog import _inline  # noqa: E402

BENCH_ISA_OFF = {
    "EXTENSION_ZBC": "0",
    "EXTENSION_ZBKX": "0",
    "EXTENSION_ZILSD": "0",
    "EXTENSION_ZCLSD": "0",
    "EXTENSION_XH3BEXTM": "0",
    "DEBUG_SUPPORT": "0",
    "BREAKPOINT_TRIGGERS": "0",
    "PMP_REGIONS": "0",
    "U_MODE": "0",
}

PARAM_RE = re.compile(r"^(parameter\s+(\w+)\s*=\s*)(.*?)(\s*,?\s*(//.*)?)$")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("hazard3", type=Path, help="Hazard3 checkout")
    ap.add_argument("--config", choices=["default", "bench-isa"], default="default")
    ap.add_argument("-o", dest="out", type=Path, required=True)
    args = ap.parse_args()

    hdl = args.hazard3.resolve() / "hdl"
    cfg_vh = args.hazard3.resolve() / "test/sim/tb_common/hdl/config_default.vh"
    values = dict(re.findall(r"^localparam\s+(\w+)\s*=\s*(.*?);", cfg_vh.read_text(), re.M))
    if args.config == "bench-isa":
        values.update(BENCH_ISA_OFF)

    patched, seen = [], set()
    for line in (hdl / "hazard3_config.vh").read_text().splitlines():
        m = PARAM_RE.match(line)
        if m and m.group(2) in values:
            line = m.group(1) + values[m.group(2)] + m.group(4)
            seen.add(m.group(2))
        patched.append(line)
    missing = set(values) - seen
    if missing:
        sys.exit(f"config names not found in hazard3_config.vh: {sorted(missing)}")

    files = [hdl / l.split(None, 1)[1].strip()
             for l in (hdl / "hazard3.f").read_text().splitlines() if l.startswith("file ")]
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "hazard3_config.vh").write_text("\n".join(patched) + "\n")
        # The patched config must win over hdl/hazard3_config.vh next to each file.
        cfg_override = Path(tmp) / "hazard3_config.vh"
        lines = [f"// Generated by hazard3_rtl.py, config {args.config}. Do not edit.\n"]
        for f in files:
            text = _inline(f, [hdl], [])
            lines += text
        out = "".join(lines)
        # Swap every inlined copy of the stock config for the patched one.
        stock = "".join(_inline(hdl / "hazard3_config.vh", [hdl], [])[1:-1])
        new = "".join(_inline(cfg_override, [hdl], [])[1:-1])
        n = out.count(stock)
        if n == 0:
            sys.exit("did not find the inlined config to replace")
        out = out.replace(stock, new)
    args.out.write_text(out)
    print(f"wrote {args.out} (config {args.config}, {n} config copies, top hazard3_cpu_2port)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
