#!/usr/bin/env python3
"""Concatenate Verilog files into one, with every `include inlined.

For designs other than uPyCore (Hazard3, the baseline) that go through
make_hammer_design.py --rtl. Each `include is looked up next to the file
that includes it, then in each -I directory, and inlined every time it
appears (Hazard3 includes its config inside every module). An include
that cannot be found is left as is, with a note.

Usage::

    flatten_verilog.py -I Hazard3/hdl -o hazard3.sv $(cat files.txt)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

INCLUDE_RE = re.compile(r'^(\s*)`include\s+"([^"]+)"(.*)$')


def _find(name: str, here: Path, dirs: list[Path]) -> Path | None:
    for d in [here, *dirs]:
        if (d / name).is_file():
            return d / name
    return None


def _inline(path: Path, dirs: list[Path], stack: list[Path]) -> list[str]:
    if path in stack:
        sys.exit(f"include cycle: {' -> '.join(p.name for p in stack + [path])}")
    out = [f"// ---- begin {path} ----\n"]
    for line in path.read_text().splitlines(keepends=True):
        m = INCLUDE_RE.match(line)
        inc = _find(m.group(2), path.parent, dirs) if m else None
        if m and inc is None:
            # Usually inside an `ifdef that is off (Hazard3's FORMAL files).
            # Left as is; the tool only fails if that branch is compiled.
            print(f"note: {path.name}: include {m.group(2)!r} not found, left in place",
                  file=sys.stderr)
            out.append(line if line.endswith("\n") else line + "\n")
        elif m:
            out += _inline(inc, dirs, stack + [path])
            if m.group(3).strip():
                out.append(m.group(3).strip() + "\n")
        else:
            out.append(line if line.endswith("\n") else line + "\n")
    out.append(f"// ---- end {path} ----\n")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", type=Path)
    ap.add_argument("-I", dest="dirs", action="append", type=Path, default=[])
    ap.add_argument("-o", dest="out", type=Path, required=True)
    args = ap.parse_args()
    lines = ["// Generated by flatten_verilog.py. Do not edit.\n"]
    for f in args.files:
        lines += _inline(f.resolve(), [d.resolve() for d in args.dirs], [])
    args.out.write_text("".join(lines))
    print(f"wrote {args.out} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
