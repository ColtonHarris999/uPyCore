#!/usr/bin/env python3
"""Write one self-contained SystemVerilog file per top for Design Compiler.

The RTL shares localparams and functions through file-scope `include of
.svh headers, so every module of a top must sit in one compilation unit
(the Yosys flow uses slang --single-unit for the same reason). This script
concatenates a top's sources from mpy_synth.TOPS, inlines every `include,
and defines SYNTHESIS, so DC reads a single file with no search path.

Usage::

    mpy_dc_unit.py mpy_core           # writes build/dc/mpy_core.sv
    mpy_dc_unit.py mpy_alu mpy_core -o somewhere/
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mpy_synth import ROOT, RTL, TOPS  # noqa: E402

INCLUDE_RE = re.compile(r'^\s*`include\s+"([^"]+)"')


def _inline(path: Path, seen_stack: list[Path]) -> list[str]:
    if path in seen_stack:
        raise SystemExit(f"include cycle: {' -> '.join(p.name for p in seen_stack + [path])}")
    out = [f"// ---- begin {path.name} ----\n"]
    for line in path.read_text().splitlines(keepends=True):
        m = INCLUDE_RE.match(line)
        if m:
            out += _inline(RTL / m.group(1), seen_stack + [path])
        else:
            out.append(line)
    if out[-1] and not out[-1].endswith("\n"):
        out.append("\n")
    out.append(f"// ---- end {path.name} ----\n")
    return out


def write_unit(top: str, out_dir: Path, skip: tuple[str, ...] = (), name: str | None = None) -> Path:
    """Write ``<out_dir>/<name or top>.sv``. ``skip`` leaves out sources that
    come from elsewhere (BaseJump's SRAM wrapper, a converted core)."""

    if top not in TOPS:
        raise SystemExit(f"unknown top {top!r}; choose from: {', '.join(TOPS)}")
    lines = [
        f"// Generated by upycore/tools/mpy_dc_unit.py for top {top}. Do not edit.\n",
        "`define SYNTHESIS\n",
    ]
    if skip:
        lines.append(f"// Not in this file: {', '.join(skip)}\n")
    for src in TOPS[top]:
        if src not in skip:
            lines += _inline(RTL / src, [])
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{name or top}.sv"
    out.write_text("".join(lines))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("tops", nargs="+", help="tops to write (see mpy_synth.py --list)")
    ap.add_argument("-o", "--out", type=Path, default=ROOT / "build" / "dc")
    args = ap.parse_args()
    for top in args.tops:
        print(write_unit(top, args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
